// A Velocity plugin: registers the Paperhive host's running servers with the proxy (put the jar in Velocity's plugins/)
dependencies {
    compileOnly(libs.velocity.api)
    annotationProcessor(libs.velocity.api) // writes velocity-plugin.json from @Plugin

    testImplementation(platform("org.junit:junit-bom:6.0.0"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

// BuildInfo.VERSION: the project's version for @Plugin (an annotation needs a compile-time constant)
val generateBuildInfo by tasks.registering {
    val version = project.version.toString()
    val out = layout.buildDirectory.dir("generated/sources/buildinfo")
    inputs.property("version", version)
    outputs.dir(out)
    doLast {
        val file = out.get().file("org/abdullahcxd/paperhive/velocity/BuildInfo.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package org.abdullahcxd.paperhive.velocity;
            |
            |/** Generated by the build. */
            |final class BuildInfo {
            |    static final String VERSION = "$version";
            |
            |    private BuildInfo() {}
            |}
            |""".trimMargin()
        )
    }
}
sourceSets.main { java.srcDir(generateBuildInfo) }
