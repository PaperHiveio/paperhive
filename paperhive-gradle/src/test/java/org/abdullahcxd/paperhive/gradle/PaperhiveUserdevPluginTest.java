package org.abdullahcxd.paperhive.gradle;

import org.gradle.api.Project;
import org.gradle.api.artifacts.Dependency;
import org.gradle.testfixtures.ProjectBuilder;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.*;

class PaperhiveUserdevPluginTest {

    @TempDir
    Path tmp;

    private Project project() {
        Project project = ProjectBuilder.builder().withProjectDir(tmp.toFile()).withName("my-plugin").build();
        project.setGroup("com.acme");
        project.setVersion("2.0");
        project.getPluginManager().apply("org.abdullahcxd.paperhive.userdev");
        return project;
    }

    @Test
    void addsTheSdkHostAndTasks() {
        Project project = project();
        String version = PaperhiveUserdevPlugin.ownVersion();
        Dependency sdk = project.getConfigurations().getByName("compileOnly").getDependencies().iterator().next();
        assertEquals("org.abdullahcxd.paperhive:paperhive-sdk:" + version, sdk.getGroup() + ":" + sdk.getName() + ":" + sdk.getVersion());
        Dependency host = project.getConfigurations().getByName(PaperhiveUserdevPlugin.HOST_CONFIGURATION).getDependencies().iterator().next();
        assertEquals("paperhive-host", host.getName());
        for (String task : new String[]{"generatePaperhiveDescriptor", "createHivePlugin", "runHive"}) assertNotNull(project.getTasks().findByName(task), task);
    }

    @Test
    void generatesTheDescriptorOnlyWithMain() throws Exception {
        Project project = project();
        PaperhiveExtension ext = project.getExtensions().getByType(PaperhiveExtension.class);
        GeneratePaperhiveDescriptor task = (GeneratePaperhiveDescriptor) project.getTasks().getByName("generatePaperhiveDescriptor");
        Path file = task.getOutputDirectory().get().getAsFile().toPath().resolve("paperhive.yml");

        task.generate();
        assertFalse(Files.exists(file), "no main: the project's own paperhive.yml is used");

        ext.getMain().set("com.acme.Main");
        ext.getServerMain().set("com.acme.Server");
        ext.getPluginDescription().set("it's here");
        task.generate();
        assertEquals("""
                # generated by the Paperhive Gradle plugin from paperhive { }
                name: 'my-plugin'
                version: '2.0'
                main: 'com.acme.Main'
                description: 'it''s here'
                server-main: 'com.acme.Server'
                """, Files.readString(file));
    }

    @Test
    void createsAStarterPluginWithoutOverwriting() throws Exception {
        Project project = project();
        CreateHivePlugin task = (CreateHivePlugin) project.getTasks().getByName("createHivePlugin");
        assertEquals("com.acme.myplugin", task.getPackageName().get());

        Path existing = tmp.resolve("src/main/resources/paperhive.yml");
        Files.createDirectories(existing.getParent());
        Files.writeString(existing, "mine");
        task.create();

        String host = Files.readString(tmp.resolve("src/main/java/com/acme/myplugin/MyPluginHivePlugin.java"));
        assertTrue(host.contains("package com.acme.myplugin;") && host.contains("class MyPluginHivePlugin extends PaperhivePlugin"), host);
        assertTrue(Files.exists(tmp.resolve("src/main/java/com/acme/myplugin/MyPluginServerPlugin.java")));
        assertEquals("mine", Files.readString(existing));
    }

    @Test
    void namesBecomeJavaNames() {
        assertEquals("MyCoolPlugin", CreateHivePlugin.className("my-cool_plugin"));
        assertEquals("Hive1x", CreateHivePlugin.className("1x"));
        assertEquals("hive1x", CreateHivePlugin.packageSegment("1-X"));
    }

}
