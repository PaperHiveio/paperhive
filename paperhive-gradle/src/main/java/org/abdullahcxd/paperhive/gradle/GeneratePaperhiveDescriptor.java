package org.abdullahcxd.paperhive.gradle;

import org.gradle.api.DefaultTask;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.CacheableTask;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.Optional;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;
import org.jspecify.annotations.NonNull;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;

/** Writes {@code paperhive.yml} (the Hive plugin descriptor) when {@code main} is set; otherwise leaves the folder empty. */
@CacheableTask
public abstract class GeneratePaperhiveDescriptor extends DefaultTask {

    @Input
    public abstract Property<String> getPluginName();

    @Input
    public abstract Property<String> getPluginVersion();

    @Input
    @Optional
    public abstract Property<String> getPluginDescription();

    @Input
    @Optional
    public abstract Property<String> getMain();

    @Input
    @Optional
    public abstract Property<String> getServerMain();

    @OutputDirectory
    public abstract DirectoryProperty getOutputDirectory();

    @TaskAction
    public void generate() {
        Path dir = getOutputDirectory().get().getAsFile().toPath();
        Path file = dir.resolve("paperhive.yml");
        try {
            Files.deleteIfExists(file);
            if (!getMain().isPresent()) return; // the project brings its own paperhive.yml
            Files.createDirectories(dir);
            Files.writeString(file, yaml());
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write " + file, e);
        }
    }

    String yaml() {
        StringBuilder out = new StringBuilder("# generated by the Paperhive Gradle plugin from paperhive { }\n");
        line(out, "name", getPluginName().get());
        line(out, "version", getPluginVersion().get());
        line(out, "main", getMain().get());
        if (getPluginDescription().isPresent()) line(out, "description", getPluginDescription().get());
        if (getServerMain().isPresent()) line(out, "server-main", getServerMain().get());
        return out.toString();
    }

    // single-quoted YAML: any text is safe once ' is doubled
    private static void line(@NonNull StringBuilder out, String key, @NonNull String value) {
        out.append(key).append(": '").append(value.replace("'", "''")).append("'\n");
    }

}
